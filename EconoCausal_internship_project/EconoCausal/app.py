"""Streamlit interface for the EconoCausal demo."""
import streamlit as st

from src.data import generate_synthetic_data
from src.dml import estimate_price_effect
from src.metrics import candidate_price_table, summarize_data

st.set_page_config(page_title="EconoCausal", page_icon="📈", layout="wide")
st.title("EconoCausal: Dynamic Pricing via Double Machine Learning")
st.caption("Educational demonstration using synthetic retail data — not real business advice.")

with st.sidebar:
    st.header("Simulation settings")
    n_samples = st.slider("Number of simulated observations", 500, 5000, 2000, step=500)
    seed = st.number_input("Random seed", min_value=0, max_value=10000, value=42, step=1)
    st.write("The simulated data-generating process has a built-in price effect of -2 units per price unit.")

data = generate_synthetic_data(n_samples=int(n_samples), random_state=int(seed))
with st.spinner("Estimating the effect with cross-fitting..."):
    result = estimate_price_effect(data)
summary = summarize_data(data)

c1, c2, c3 = st.columns(3)
c1.metric("Average price", f"{summary['average_price']:.2f}")
c2.metric("Average units sold", f"{summary['average_units_sold']:.1f}")
c3.metric("Estimated price effect", f"{result['effect_per_price_unit']:.2f} units")

st.subheader("Price and demand")
st.scatter_chart(data, x="price", y="units_sold")
st.write(
    "The estimated effect describes the model's estimated change in units sold "
    "for a one-unit increase in price, after adjusting for the listed controls."
)

st.subheader("Illustrative candidate-price comparison")
table = candidate_price_table(data, result["effect_per_price_unit"])
st.dataframe(table, use_container_width=True, hide_index=True)
st.line_chart(table.set_index("candidate_price")[["illustrative_revenue"]])

st.subheader("Interpretation and limitations")
st.markdown(
    "- Data are generated by code, not collected from customers.\n"
    "- A causal interpretation depends on assumptions, including adequate observed confounder control.\n"
    "- The candidate-price table is a simple illustration, not a production pricing optimizer.\n"
    "- Validate any method on suitable real data before using it for business decisions."
)
with st.expander("Technical details"):
    st.json(result)
